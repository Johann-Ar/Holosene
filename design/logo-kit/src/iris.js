export const cssConic = (stops = IRIS_STOPS) =>
  `conic-gradient(from ${IRIS_FROM_DEG}deg, ${stops.map(([p, c]) => `${c} ${(p * 360).toFixed(1)}deg`).join(', ')})`;

const hex = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
/** Couleur RGB [0..1] pour un angle écran (radians, atan2(dy, dx) avec y vers le bas). */
export function sampleIris(angleRad, stops = IRIS_STOPS) {
  // angle CSS : 0 = haut, horaire  → t ∈ [0,1)
  let deg = (angleRad * 180) / Math.PI + 90 - IRIS_FROM_DEG;
  let t = (((deg % 360) + 360) % 360) / 360;
  for (let i = 0; i < stops.length - 1; i++) {
    const [p0, c0] = stops[i], [p1, c1] = stops[i + 1];
    if (t >= p0 && t <= p1) {
      const k = (t - p0) / (p1 - p0 || 1), a = hex(c0), b = hex(c1);
      return a.map((v, j) => v + (b[j] - v) * k);
    }
  }
  return hex(stops[0][1]);
}

/** Texture 1D (Uint8 RGBA, largeur N) à envoyer au shader : u = t de la roue. */
export function irisLUT(N = 1024, stops = IRIS_STOPS) {
  const out = new Uint8Array(N * 4);
  for (let i = 0; i < N; i++) {
    const t = i / N, ang = ((t * 360 + IRIS_FROM_DEG - 90) * Math.PI) / 180;
    const c = sampleIris(ang, stops);
    out.set([c[0] * 255, c[1] * 255, c[2] * 255, 255], i * 4);
  }
  return out;
}
